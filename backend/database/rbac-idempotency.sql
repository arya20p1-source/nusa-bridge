-- ==========================================================================
-- NUSABRIDGE - RBAC & IDEMPOTENCY MIGRATION
-- File: database/rbac-idempotency.sql
--
-- Jalankan SATU KALI pada database Supabase yang sudah ada (SQL Editor):
--   psql "$DATABASE_URL" -f backend/database/rbac-idempotency.sql
-- atau copy-paste seluruh isi file ini ke Supabase SQL Editor.
--
-- Migrasi ini menambahkan:
--   * kolom idempotency_key & request_hash pada tabel rfqs;
--   * tabel idempotency_keys untuk klaim request secara atomik;
--   * unique index pencegah dua RFQ dengan pembeli + idempotency key sama;
--   * RLS untuk idempotency_keys (service role backend tetap bisa akses).
--
-- Tanpa migrasi ini backend tetap berjalan memakai penjagaan di level proses,
-- tetapi perlindungan setelah restart / multi-instance hanya aktif setelah
-- migrasi dijalankan.
-- ==========================================================================

begin;

-- 1. Kolom idempotency pada RFQ
-- ==========================================================================
alter table public.rfqs
  add column if not exists idempotency_key text;

alter table public.rfqs
  add column if not exists request_hash text;

create index if not exists rfqs_idempotency_key_idx
  on public.rfqs (idempotency_key)
  where idempotency_key is not null;

-- Scope pembeli = user id (bila login) atau email (bila guest).
-- Satu key hanya boleh menghasilkan satu RFQ per pembeli.
create unique index if not exists rfqs_idempotency_scope_uidx
  on public.rfqs (
    idempotency_key,
    coalesce(buyer_user_id::text, lower(buyer_email))
  )
  where idempotency_key is not null;

-- 2. Tabel idempotency_keys
-- ==========================================================================
create table if not exists public.idempotency_keys (
  id              bigint generated by default as identity primary key,
  scope           text not null,
  idempotency_key text not null,
  request_hash    text not null,
  endpoint        text,
  status          text not null default 'processing'
                  check (status in ('processing', 'completed')),
  response_status integer,
  response_body   jsonb,
  resource_type   text,
  resource_id     text,
  locked_at       timestamptz not null default now(),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);

create unique index if not exists idempotency_keys_scope_key_uidx
  on public.idempotency_keys (scope, idempotency_key);

create index if not exists idempotency_keys_status_idx
  on public.idempotency_keys (status, locked_at);

create index if not exists idempotency_keys_resource_idx
  on public.idempotency_keys (resource_type, resource_id);

-- 3. Trigger updated_at (fungsi sudah dibuat oleh schema.sql/lanjutan.sql)
-- ==========================================================================
do $$
begin
  if exists (
    select 1
    from pg_proc
    where proname = 'set_updated_at'
      and pronamespace = 'public'::regnamespace
  ) then
    drop trigger if exists idempotency_keys_set_updated_at on public.idempotency_keys;
    create trigger idempotency_keys_set_updated_at
      before update on public.idempotency_keys
      for each row execute function public.set_updated_at();
  end if;
end
$$;

-- 4. RLS: backend memakai service_role sehingga tetap melewati RLS.
-- Tidak ada policy publik untuk tabel internal ini.
-- ==========================================================================
alter table public.idempotency_keys enable row level security;

commit;

