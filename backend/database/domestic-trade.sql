create table if not exists public.product_offers (
  id                   bigint generated by default as identity primary key,
  code                 text not null unique,
  product_id           bigint not null references public.products(id) on delete cascade,
  seller_id            bigint references public.users(id) on delete set null,
  trade_scope          text not null check (trade_scope in ('domestic', 'export', 'import')),
  price                numeric(16,2) not null default 0 check (price >= 0),
  currency             text not null default 'IDR' check (currency in ('IDR', 'USD')),
  unit                 text not null,
  moq                  numeric(14,2) not null default 1 check (moq > 0),
  incoterm             text check (incoterm in ('FOB', 'CIF', 'CNF', 'EXW', 'FCA', 'DDP')),
  origin_region_id     bigint references public.trade_regions(id) on delete set null,
  port_of_loading_id   bigint references public.trade_ports(id) on delete set null,
  destination_port_id  bigint references public.trade_ports(id) on delete set null,
  stock                numeric(14,2) not null default 0 check (stock >= 0),
  lead_time_days       integer not null default 7 check (lead_time_days >= 0),
  status               text not null default 'active' check (status in ('draft', 'active', 'paused', 'archived')),
  metadata             jsonb not null default '{}'::jsonb,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  unique (product_id, trade_scope, currency)
);

create index if not exists product_offers_product_idx on public.product_offers (product_id);
create index if not exists product_offers_seller_idx on public.product_offers (seller_id);
create index if not exists product_offers_scope_idx on public.product_offers (trade_scope, status);
create index if not exists product_offers_region_idx on public.product_offers (origin_region_id);

-- Penawaran domestik (IDR) otomatis dari 50 produk yang sudah ada.
insert into public.product_offers (
  code, product_id, seller_id, trade_scope, price, currency, unit, moq,
  incoterm, origin_region_id, port_of_loading_id, stock, lead_time_days, status
)
select
  'off_dom_' || p.code,
  p.id,
  p.seller_id,
  'domestic',
  round((p.price * 16000) / 500) * 500,
  'IDR',
  p.unit,
  p.moq,
  'FOB',
  (
    select r.id from public.trade_regions r
    where r.type = 'province' and p.origin ilike '%' || r.name || '%'
    limit 1
  ),
  (
    select tp.id from public.trade_ports tp
    where tp.scope = 'domestic'
      and (coalesce(p.port_of_loading, p.shipping, '') ilike '%' || tp.name || '%')
    limit 1
  ),
  greatest(p.stock, 100),
  5,
  'active'
from public.products p
where p.deleted_at is null
on conflict (product_id, trade_scope, currency) do nothing;

-- Penawaran ekspor (USD) dari produk yang sama.
insert into public.product_offers (
  code, product_id, seller_id, trade_scope, price, currency, unit, moq,
  incoterm, origin_region_id, port_of_loading_id, stock, lead_time_days, status
)
select
  'off_exp_' || p.code,
  p.id,
  p.seller_id,
  'export',
  p.price,
  'USD',
  p.unit,
  p.moq,
  coalesce(p.incoterms, 'FOB'),
  (
    select r.id from public.trade_regions r
    where r.type = 'province' and p.origin ilike '%' || r.name || '%'
    limit 1
  ),
  (
    select tp.id from public.trade_ports tp
    where tp.scope = 'domestic'
      and (coalesce(p.port_of_loading, p.shipping, '') ilike '%' || tp.name || '%')
    limit 1
  ),
  greatest(p.stock, 100),
  14,
  'active'
from public.products p
where p.deleted_at is null
on conflict (product_id, trade_scope, currency) do nothing;

