create table if not exists public.trade_orders (
  id                    bigint generated by default as identity primary key,
  code                  text not null unique,
  order_no              text not null unique,
  buyer_id              bigint references public.users(id) on delete set null,
  seller_id             bigint references public.users(id) on delete set null,
  offer_id              bigint references public.product_offers(id) on delete set null,
  product_id            bigint references public.products(id) on delete set null,
  trade_scope           text not null check (trade_scope in ('domestic', 'export', 'import')),
  quantity              numeric(14,2) not null check (quantity > 0),
  unit                  text not null,
  unit_price            numeric(16,2) not null default 0 check (unit_price >= 0),
  currency              text not null default 'IDR' check (currency in ('IDR', 'USD')),
  subtotal              numeric(18,2) not null default 0 check (subtotal >= 0),
  shipping_cost         numeric(18,2) not null default 0 check (shipping_cost >= 0),
  insurance_cost        numeric(18,2) not null default 0 check (insurance_cost >= 0),
  tax_amount            numeric(18,2) not null default 0 check (tax_amount >= 0),
  total_amount          numeric(18,2) not null default 0 check (total_amount >= 0),
  incoterm              text check (incoterm in ('FOB', 'CIF', 'CNF', 'EXW', 'FCA', 'DDP')),
  origin_region_id      bigint references public.trade_regions(id) on delete set null,
  destination_region_id bigint references public.trade_regions(id) on delete set null,
  destination_port_id   bigint references public.trade_ports(id) on delete set null,
  shipping_address      text,
  status                text not null default 'draft'
                        check (status in ('draft', 'pending_payment', 'paid', 'processing',
                                          'shipped', 'delivered', 'completed', 'cancelled', 'disputed')),
  payment_status        text not null default 'unpaid'
                        check (payment_status in ('unpaid', 'partial', 'paid', 'refunded')),
  notes                 text,
  metadata              jsonb not null default '{}'::jsonb,
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now()
);

