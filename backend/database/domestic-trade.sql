create or replace view public.v_domestic_offers as
select
  o.id,
  o.code,
  p.code as product_code,
  p.name,
  p.category,
  p.image,
  o.price,
  o.currency,
  o.unit,
  o.moq,
  o.stock,
  o.lead_time_days,
  r.name as origin_region,
  r.island as origin_island,
  tp.name as port_of_loading,
  o.status
from public.product_offers o
join public.products p on p.id = o.product_id
left join public.trade_regions r on r.id = o.origin_region_id
left join public.trade_ports tp on tp.id = o.port_of_loading_id
where o.trade_scope = 'domestic'
  and o.status = 'active'
  and p.deleted_at is null;

create or replace view public.v_export_offers as
select
  o.id,
  o.code,
  p.code as product_code,
  p.name,
  p.category,
  p.image,
  o.price,
  o.currency,
  o.unit,
  o.moq,
  o.stock,
  o.lead_time_days,
  r.name as origin_region,
  r.island as origin_island,
  tp.name as port_of_loading,
  o.status
from public.product_offers o
join public.products p on p.id = o.product_id
left join public.trade_regions r on r.id = o.origin_region_id
left join public.trade_ports tp on tp.id = o.port_of_loading_id
where o.trade_scope = 'export'
  and o.status = 'active'
  and p.deleted_at is null;

create or replace view public.v_order_summary as
select
  o.id,
  o.code,
  o.order_no,
  o.trade_scope,
  o.currency,
  o.quantity,
  o.unit,
  o.subtotal,
  o.shipping_cost,
  o.tax_amount,
  o.total_amount,
  o.status,
  o.payment_status,
  o.created_at,
  p.name as product_name,
  b.name as buyer_name,
  b.company as buyer_company,
  s.name as seller_name,
  s.company as seller_company,
  dr.name as destination_region,
  dp.name as destination_port
from public.trade_orders o
left join public.products p on p.id = o.product_id
left join public.users b on b.id = o.buyer_id
left join public.users s on s.id = o.seller_id
left join public.trade_regions dr on dr.id = o.destination_region_id
left join public.trade_ports dp on dp.id = o.destination_port_id;

